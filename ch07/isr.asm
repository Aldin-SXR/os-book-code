; The common tail of all 48 stubs. By the time isr_dispatch is called the
; stack holds a struct registers and esp is its address.
isr_common:
    pusha                 ; edi esi ebp esp ebx edx ecx eax

    mov ax, ds
    push eax              ; the interrupted code's ds

    mov ax, KERNEL_DATA   ; ours, whoever ran before
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    push esp              ; struct registers *
    call isr_dispatch
    add esp, 4

    pop eax               ; give the old ds back
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax

    popa
    add esp, 8            ; the vector and the error code

    ; iret, not ret: it restores eip, cs and eflags together, which is the
    ; only way to put the interrupt flag back with the instruction pointer.
    ; ret would pop eip alone and leave cs and eflags on the stack.
    iret
