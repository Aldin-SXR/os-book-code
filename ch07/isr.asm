; spark -- isr.asm
;
; The assembly entry points for all 48 vectors spark implements.
;
; A handler cannot be an ordinary C function. The processor does not call one:
; it pushes its own words and jumps, and the sequence has to end in iret
; rather than ret. A C function would also destroy the registers the
; interrupted code was using before saving them.
;
; Each stub therefore normalises the differences and hands C a frame it can
; read as a struct registers:
;
;   * Seven vectors push an error code and the rest do not. The stubs for the
;     rest push a zero, so that every frame has one layout.
;   * Nothing tells the handler which vector was raised, so each stub pushes
;     its own number.
;   * pusha saves the eight general registers, and ds is reloaded by hand:
;     an interrupt taken from user code arrives with the user's data segment
;     still loaded.
;
; The stubs are generated by macros: they differ only in a number.

bits 32
section .text

KERNEL_DATA equ 0x10          ; must match kernel/gdt.h

extern isr_dispatch

; A vector with no error code: push a zero in its place so that every frame
; has the same layout.
%macro ISR_NOERR 1
global isr%1
isr%1:
    push dword 0
    push dword %1
    jmp isr_common
%endmacro

; A vector with an error code, which the processor has already pushed. Only
; the vector number is added.
%macro ISR_ERR 1
global isr%1
isr%1:
    push dword %1
    jmp isr_common
%endmacro

; The sixteen hardware lines, at the vectors pic_init remaps them to. None
; carries an error code.
%macro IRQ_STUB 2
global irq%1
irq%1:
    push dword 0
    push dword %2
    jmp isr_common
%endmacro

